-- 1. Buat tabel wishes (papan kertas ucapan & doa untuk Bu Dewi)
CREATE TABLE IF NOT EXISTS public.wishes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  message TEXT NOT NULL,
  badge TEXT DEFAULT 'Ucapan #01|note-cream',
  likes INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Aktifkan Row Level Security (RLS)
ALTER TABLE public.wishes ENABLE ROW LEVEL SECURITY;

-- 3. Berikan hak akses ke role anon & authenticated (untuk akses dari frontend)
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.wishes TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- 4. Kebijakan RLS (Policies)
DROP POLICY IF EXISTS "Public read" ON public.wishes;
CREATE POLICY "Public read"
  ON public.wishes
  FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Public insert" ON public.wishes;
CREATE POLICY "Public insert"
  ON public.wishes
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Public update" ON public.wishes;
CREATE POLICY "Public update"
  ON public.wishes
  FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Public delete" ON public.wishes;
CREATE POLICY "Public delete"
  ON public.wishes
  FOR DELETE
  TO anon, authenticated
  USING (true);
